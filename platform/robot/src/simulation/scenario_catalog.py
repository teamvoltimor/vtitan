"""Scenario catalogs backing the RViz live visualizer and two pytest batteries.

The Obstacles Challenge catalog loads ``*_metadata.json`` fixtures generated by
the Go generator (``platform/robot-go/cmd/simgen``, part of the robot-go
module) — the same generator that produces the real robot's scenario
metadata — so visualizing "scenario N" here means watching a real
official-generator layout, including the actual WRO 2026 36-scenario
traffic-sign table (``internal/simgen/generate/scenarios.go``).

The Open Challenge catalog is generated on demand: it covers all 640 legal
combinations of corridor widths, starting section, travel direction and starting
cell (4 sections × 2 directions × 16 width combinations × 4 narrow or 6 wide
cells). No fixtures need to be committed for it.

To regenerate the Obstacles fixtures (e.g. after a sign-table change in Go),
from ``platform/robot-go``:

    go run ./cmd/simgen generate --challenge obstacles --num-scenarios 16 --seed 2026 --output-dir /tmp/fixtures/obstacles

then copy only the ``*_metadata.json`` files (discard the ``.sdf``/``.svg``
siblings) into ``tests/fixtures/scenarios/obstacles/`` here. The committed Open
Challenge fixtures (``tests/fixtures/scenarios/open/``) are retained for the
unit-test battery and can still be loaded with :func:`all_test_scenarios`.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import TYPE_CHECKING, Any

from shared.config.constants import CompetitionSpecs, CorridorDimensions

if TYPE_CHECKING:
    from shared.domain.models import ScenarioMetadata
from shared.domain.enums import Direction, Section

from src.simulation.scenario_builder import build_open_metadata

_FIXTURES_DIR = Path(__file__).resolve().parents[2] / "tests" / "fixtures" / "scenarios"


@dataclass(frozen=True, slots=True)
class NamedScenario:
    """One (metadata, laps, seed) input, labeled after its Go-generated fixture."""

    label: str
    metadata: dict[str, Any]
    laps: int
    seed: int


def _load_fixture_scenarios(
    subdir: str,
    label_prefix: str,
    fixtures_dir: Path | None = None,
) -> list[NamedScenario]:
    """Load every ``*_metadata.json`` under ``fixtures_dir/subdir``.

    ``fixtures_dir`` overrides the committed fixture set. The committed one is
    deliberately small (16 obstacles, 28 open) because it is the unit-test
    battery and has to stay fast; statistical questions -- how often some
    configuration occurs, how a change behaves across the space rather than on
    one sample -- need hundreds, which is what the override is for. Generate
    them with the same Go generator and a pinned seed (see the module
    docstring), so a corpus is reproducible without being committed.
    """
    root = fixtures_dir if fixtures_dir is not None else _FIXTURES_DIR / subdir
    scenarios = []
    for path in sorted(root.glob("*_metadata.json")):
        meta = json.loads(path.read_text())
        sc = meta["starting_conditions"]
        label = f"{label_prefix}_{meta['scenario_id']:04d}[{sc['section']}/{sc['direction']}]"
        scenarios.append(NamedScenario(label, meta, CompetitionSpecs.OPEN_CHALLENGE_LAPS, seed=meta["scenario_id"]))
    return scenarios


def all_test_scenarios(fixtures_dir: Path | None = None) -> list[NamedScenario]:
    """The Go-generated Open Challenge scenario fixtures."""
    return _load_fixture_scenarios("open", "go_open", fixtures_dir)


def all_obstacles_demo_scenarios(fixtures_dir: Path | None = None) -> list[NamedScenario]:
    """The Go-generated Obstacles Challenge scenario fixtures (signs + parking).

    Every scenario has both a sign layout (from the real 36-scenario table)
    and a parking lot — the Go generator always builds them together for the
    Obstacles Challenge, matching the real competition rules.

    Pass ``fixtures_dir`` to run against a larger generated corpus instead of
    the committed 16 — see :func:`_load_fixture_scenarios`.
    """
    return _load_fixture_scenarios("obstacles", "go_obstacles", fixtures_dir)


_OPEN_SECTIONS = (Section.SOUTH, Section.NORTH, Section.EAST, Section.WEST)
"""Canonical order used when enumerating the dynamic Open Challenge catalog."""

_NARROW_MM = int(CorridorDimensions.NARROW * 1000)
_WIDE_MM = int(CorridorDimensions.WIDE * 1000)


@dataclass(frozen=True, slots=True)
class CorridorWidthSet:
    """One complete Open Challenge corridor-width assignment, in millimetres."""

    south_mm: int
    north_mm: int
    east_mm: int
    west_mm: int

    @classmethod
    def from_bits(cls, bits: int) -> CorridorWidthSet:
        """Map a 4-bit value to the four corridor widths."""
        return cls(
            south_mm=_WIDE_MM if bits & 0b0001 else _NARROW_MM,
            north_mm=_WIDE_MM if bits & 0b0010 else _NARROW_MM,
            east_mm=_WIDE_MM if bits & 0b0100 else _NARROW_MM,
            west_mm=_WIDE_MM if bits & 0b1000 else _NARROW_MM,
        )

    def width_mm_for(self, section: Section) -> int:
        """Width of the requested corridor."""
        return int(getattr(self, f"{section.value.lower()}_mm"))

    def is_wide(self, section: Section) -> bool:
        """True if the requested corridor is the wide width."""
        return self.width_mm_for(section) == _WIDE_MM

    def start_cell_count(self, section: Section) -> int:
        """Legal starting-cell count for this corridor width."""
        return 6 if self.is_wide(section) else 4

    def as_dict(self) -> dict[str, int]:
        """Return the widths in the shape expected by build_open_metadata."""
        return {
            "south": self.south_mm,
            "north": self.north_mm,
            "east": self.east_mm,
            "west": self.west_mm,
        }


@dataclass(frozen=True, slots=True)
class OpenChallengeScenarioParams:
    """Parameters that uniquely identify one Open Challenge scenario."""

    index: int
    direction: Direction
    widths: CorridorWidthSet
    section: Section
    start_cell: int

    @property
    def label(self) -> str:
        """Short human-readable label, matching the visualizer catalog format."""
        dir_abbrev = "cw" if self.direction is Direction.CLOCKWISE else "ccw"
        return f"open_{self.index:04d}[{self.section.value}/{dir_abbrev}]"

    def to_metadata(self) -> ScenarioMetadata:
        """Build the full scenario metadata for this parameter set."""
        return build_open_metadata(
            self.widths.as_dict(),
            self.section,
            self.direction,
            scenario_id=self.index,
            start_cell=self.start_cell,
        )

    def to_named_scenario(
        self,
        laps: int | None = None,
        seed: int | None = None,
    ) -> NamedScenario:
        """Convert to the catalog tuple used by the visualizer and tests."""
        metadata = self.to_metadata()
        return NamedScenario(
            label=self.label,
            metadata=metadata.model_dump(),
            laps=laps if laps is not None else CompetitionSpecs.OPEN_CHALLENGE_LAPS,
            seed=seed if seed is not None else self.index,
        )


@dataclass(frozen=True, slots=True)
class OpenChallengeScenarioSpace:
    """The complete legal Open Challenge scenario space.

    Encapsulates the enumeration order and provides index-to-parameter mapping
    without hard-coding the 640 count or the bit/section/cell layout.
    """

    sections: tuple[Section, ...] = _OPEN_SECTIONS
    directions: tuple[Direction, ...] = (
        Direction.CLOCKWISE,
        Direction.COUNTERCLOCKWISE,
    )
    _params: tuple[OpenChallengeScenarioParams, ...] = field(init=False, repr=False, compare=False)

    def __post_init__(self) -> None:
        # Build the deterministic enumeration once.  dataclass(frozen) allows
        # mutation only inside __post_init__ via object.__setattr__.
        params: list[OpenChallengeScenarioParams] = []
        index = 0
        for direction in self.directions:
            for bits in range(16):
                widths = CorridorWidthSet.from_bits(bits)
                for section in self.sections:
                    for cell in range(widths.start_cell_count(section)):
                        params.append(
                            OpenChallengeScenarioParams(
                                index=index,
                                direction=direction,
                                widths=widths,
                                section=section,
                                start_cell=cell,
                            )
                        )
                        index += 1
        object.__setattr__(self, "_params", tuple(params))

    @property
    def size(self) -> int:
        """Total number of scenarios in this space."""
        return len(self._params)

    def params_for_index(self, index: int) -> OpenChallengeScenarioParams:
        """Return the parameter set for a scenario index, wrapping modulo size."""
        return self._params[index % self.size]

    def all_params(self) -> tuple[OpenChallengeScenarioParams, ...]:
        """All parameter sets in deterministic order."""
        return self._params


# Singleton instance covering the full legal Open Challenge space.
_OPEN_CHALLENGE_SPACE = OpenChallengeScenarioSpace()


def open_scenario_by_index(index: int) -> NamedScenario:
    """Generate one Open Challenge scenario metadata deterministically."""
    return _OPEN_CHALLENGE_SPACE.params_for_index(index).to_named_scenario()


def all_open_scenarios() -> list[NamedScenario]:
    """The complete deterministic Open Challenge catalog."""
    return [params.to_named_scenario() for params in _OPEN_CHALLENGE_SPACE.all_params()]


def find_scenario(selector: str, scenarios: list[NamedScenario]) -> NamedScenario:
    """Resolve a CLI selector to one scenario: an index, or a label substring.

    Numeric selectors wrap modulo the catalog size, so e.g. ``--scenario 640``
    with a 640-scenario Open Challenge catalog resolves to scenario 0.
    """
    if selector.isdigit():
        idx = int(selector) % len(scenarios)
        return scenarios[idx]
    matches = [s for s in scenarios if selector.lower() in s.label.lower()]
    if not matches:
        msg = f"No scenario label contains {selector!r}."
        raise ValueError(msg)
    if len(matches) > 1:
        labels = ", ".join(m.label for m in matches)
        msg = f"{selector!r} matches multiple scenarios: {labels}"
        raise ValueError(msg)
    return matches[0]
