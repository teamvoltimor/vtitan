package imu

import "math"

// Quaternion is a unit quaternion in (x, y, z, w) order, matching
// geometry_msgs/Quaternion field order.
type Quaternion struct {
	X, Y, Z, W float64
}

// QuaternionFromEuler derives an orientation quaternion from RVC-mode
// Euler angles (in degrees), since the BNO08x's UART-RVC mode reports
// Euler angles directly and never a quaternion. This mirrors
// platform/robot/src/hardware/imu/bno08x/utils.py's
// calculate_quaternion_from_euler, which calls
// scipy.spatial.transform.Rotation.from_euler("xyz", [roll, pitch, yaw],
// degrees=True) — i.e. intrinsic rotations about body X (roll), then body Y
// (pitch), then body Z (yaw), which is the standard aerospace ZYX
// (yaw-pitch-roll) formula below. Verified byte-for-byte against golden
// vectors generated by that exact scipy call (see quaternion_test.go) —
// do not hand-edit the formula without re-deriving against scipy, a wrong
// sign here silently corrupts every orientation reading published.
func QuaternionFromEuler(yawDeg, pitchDeg, rollDeg float64) Quaternion {
	const degToRadHalf = math.Pi / 180 / 2

	yaw := yawDeg * degToRadHalf
	pitch := pitchDeg * degToRadHalf
	roll := rollDeg * degToRadHalf

	sy, cy := math.Sincos(yaw)
	sp, cp := math.Sincos(pitch)
	sr, cr := math.Sincos(roll)

	return Quaternion{
		X: cy*cp*sr - sy*sp*cr,
		Y: cy*sp*cr + sy*cp*sr,
		Z: sy*cp*cr - cy*sp*sr,
		W: cy*cp*cr + sy*sp*sr,
	}
}
